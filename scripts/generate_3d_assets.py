#!/usr/bin/env python3
"""Procedural 3D Game-Ready Asset Generator for Project DEADZONE.
Outputs low-poly .obj files directly into Assets/_Project/Art/Models/.
Follows Docs/Design/ASSET_CONTRACT_GATE1.md budgets and standards.
"""

import math
import os
from pathlib import Path

OUTPUT_DIR = Path("E:/gamedev/Project Deadzone/Deadzone_Game/Assets/_Project/Art/Models")

class ObjBuilder:
    def __init__(self, name: str):
        self.name = name
        self.vertices = []
        self.normals = []
        self.uvs = []
        self.faces = []

    def add_vertex(self, x: float, y: float, z: float) -> int:
        self.vertices.append((round(x, 4), round(y, 4), round(z, 4)))
        return len(self.vertices)

    def add_normal(self, nx: float, ny: float, nz: float) -> int:
        self.normals.append((round(nx, 4), round(ny, 4), round(nz, 4)))
        return len(self.normals)

    def add_uv(self, u: float, v: float) -> int:
        self.uvs.append((round(u, 4), round(v, 4)))
        return len(self.uvs)

    def add_quad(self, v1, v2, v3, v4, normal_idx=1, uv_quad=(1, 2, 3, 4)):
        u1, u2, u3, u4 = uv_quad
        # Split quad into two triangles (1-2-3 and 1-3-4)
        self.faces.append([(v1, u1, normal_idx), (v2, u2, normal_idx), (v3, u3, normal_idx)])
        self.faces.append([(v1, u1, normal_idx), (v3, u3, normal_idx), (v4, u4, normal_idx)])

    def add_box(self, cx, cy, cz, sx, sy, sz):
        """Adds an axis-aligned box with proper outward normals and planar UVs."""
        hx, hy, hz = sx * 0.5, sy * 0.5, sz * 0.5
        x0, x1 = cx - hx, cx + hx
        y0, y1 = cy - hy, cy + hy
        z0, z1 = cz - hz, cz + hz

        # Normals
        n_up = self.add_normal(0, 1, 0)
        n_down = self.add_normal(0, -1, 0)
        n_north = self.add_normal(0, 0, 1)
        n_south = self.add_normal(0, 0, -1)
        n_east = self.add_normal(1, 0, 0)
        n_west = self.add_normal(-1, 0, 0)

        # UV corners
        uv1 = self.add_uv(0.0, 0.0)
        uv2 = self.add_uv(1.0, 0.0)
        uv3 = self.add_uv(1.0, 1.0)
        uv4 = self.add_uv(0.0, 1.0)
        uv_std = (uv1, uv2, uv3, uv4)

        # 8 corners
        v000 = self.add_vertex(x0, y0, z0)
        v100 = self.add_vertex(x1, y0, z0)
        v110 = self.add_vertex(x1, y1, z0)
        v010 = self.add_vertex(x0, y1, z0)
        v001 = self.add_vertex(x0, y0, z1)
        v101 = self.add_vertex(x1, y0, z1)
        v111 = self.add_vertex(x1, y1, z1)
        v011 = self.add_vertex(x0, y1, z1)

        # Top face (+Y)
        self.add_quad(v011, v111, v110, v010, n_up, uv_std)
        # Bottom face (-Y)
        self.add_quad(v000, v100, v101, v001, n_down, uv_std)
        # North face (+Z)
        self.add_quad(v001, v101, v111, v011, n_north, uv_std)
        # South face (-Z)
        self.add_quad(v100, v000, v010, v110, n_south, uv_std)
        # East face (+X)
        self.add_quad(v101, v100, v110, v111, n_east, uv_std)
        # West face (-X)
        self.add_quad(v000, v001, v011, v010, n_west, uv_std)

    def write_obj(self, filepath: Path):
        filepath.parent.mkdir(parents=True, exist_ok=True)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(f"# Wavefront OBJ - {self.name}\n")
            f.write(f"# Generated by DEADZONE Art Automation\n")
            f.write(f"o {self.name}\n\n")

            for v in self.vertices:
                f.write(f"v {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}\n")
            f.write("\n")

            for vn in self.normals:
                f.write(f"vn {vn[0]:.4f} {vn[1]:.4f} {vn[2]:.4f}\n")
            f.write("\n")

            for vt in self.uvs:
                f.write(f"vt {vt[0]:.4f} {vt[1]:.4f}\n")
            f.write("\n")

            f.write(f"s 1\n")
            for face in self.faces:
                f.write("f " + " ".join(f"{v}/{vt}/{vn}" for v, vt, vn in face) + "\n")
        print(f"Exported: {filepath} ({len(self.faces)} triangles, {len(self.vertices)} verts)")


