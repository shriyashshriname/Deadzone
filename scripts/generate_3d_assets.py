def generate_hazard_barrel():
    b = ObjBuilder("HazardBarrel")
    # 16-sided cylinder for industrial 55-gal barrel (radius 0.3m, height 0.95m)
    segments = 16
    radius = 0.30
    height = 0.95
    levels = [0.0, 0.04, 0.28, 0.32, 0.63, 0.67, 0.91, 0.95]
    radii   = [0.29, 0.31, 0.30, 0.32, 0.32, 0.30, 0.31, 0.29] # ribs at 0.3m and 0.65m

    # Generate rings of vertices
    rings = []
    for y, r in zip(levels, radii):
        ring = []
        for i in range(segments):
            angle = 2.0 * math.pi * i / segments
            x = r * math.cos(angle)
            z = r * math.sin(angle)
            ring.append(b.add_vertex(x, y, z))
        rings.append(ring)

    # Wall normals and UVs
    n_out = b.add_normal(0, 0, 1)
    uv_std = (b.add_uv(0, 0), b.add_uv(1, 0), b.add_uv(1, 1), b.add_uv(0, 1))

    # Connect rings
    for lvl in range(len(levels) - 1):
        r1 = rings[lvl]
        r2 = rings[lvl + 1]
        for i in range(segments):
            i_next = (i + 1) % segments
            b.add_quad(r1[i], r1[i_next], r2[i_next], r2[i], n_out, uv_std)

    # Top Cap
    n_up = b.add_normal(0, 1, 0)
    top_center = b.add_vertex(0, height, 0)
    top_ring = rings[-1]
    uv_c = b.add_uv(0.5, 0.5)
    for i in range(segments):
        i_next = (i + 1) % segments
        b.faces.append([(top_center, uv_c, n_up), (top_ring[i], uv_c, n_up), (top_ring[i_next], uv_c, n_up)])

    # Bottom Cap
    n_down = b.add_normal(0, -1, 0)
    bot_center = b.add_vertex(0, 0, 0)
    bot_ring = rings[0]
    for i in range(segments):
        i_next = (i + 1) % segments
        b.faces.append([(bot_center, uv_c, n_down), (bot_ring[i_next], uv_c, n_down), (bot_ring[i], uv_c, n_down)])

    # Top Bung Plugs
    b.add_box(0.12, height + 0.015, 0.08, 0.06, 0.03, 0.06)
    b.add_box(-0.12, height + 0.012, -0.06, 0.04, 0.025, 0.04)

    b.write_obj(OUTPUT_DIR / "Props" / "HazardBarrel.obj")


